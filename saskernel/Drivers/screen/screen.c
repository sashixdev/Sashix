void screen_init(void) {
    uint8_t *vbe = (uint8_t *)0x5000;
    uint16_t w = *(uint16_t *)(vbe + 0x12);
    uint16_t h = *(uint16_t *)(vbe + 0x14);
    uint16_t pitch = *(uint16_t *)(vbe + 0x10);
    uint8_t bits = *(vbe + 0x19);
    uint32_t phys = *(uint32_t *)(vbe + 0x28);

    if (w >= 640 && w <= 1920) g_scr_w = w;
    if (h >= 480 && h <= 1080) g_scr_h = h;
    if (bits == 24 || bits == 32) bpp = bits;
    pitch_bytes = (pitch > 0) ? pitch : (uint32_t)(g_scr_w * (bpp / 8));
    if (phys != 0) lfb = (uint32_t *)phys;
}

void screen_set_brightness(uint8_t pct) {
    if (pct < 20) pct = 20;
    if (pct > 100) pct = 100;
    cur_bright = pct;
}

static inline uint32_t apply_bright(uint32_t col) {
    if (cur_bright >= 100) return col;
    uint32_t r = (((col >> 16) & 0xFF) * cur_bright) / 100;
    uint32_t g = (((col >> 8)  & 0xFF) * cur_bright) / 100;
    uint32_t b = ((col & 0xFF) * cur_bright) / 100;
    return (r << 16) | (g << 8) | b;
}

void screen_clear(uint32_t color) {
    uint32_t c = apply_bright(color);
    uint32_t total = (uint32_t)(g_scr_w * g_scr_h);
    asm volatile ("cld; rep stosl" : : "D"(back_buf), "a"(c), "c"(total) : "memory");
}

void screen_rect(int x, int y, int w, int h, uint32_t color) {
    if (x < 0) { w += x; x = 0; }
    if (y < 0) { h += y; y = 0; }
    if (x + w > g_scr_w) w = g_scr_w - x;
    if (y + h > g_scr_h) h = g_scr_h - y;
    if (w <= 0 || h <= 0) return;

    uint32_t c = apply_bright(color);
    for (int row = 0; row < h; row++) {
        uint32_t *dst = back_buf + (y + row) * g_scr_w + x;
        for (int col = 0; col < w; col++) {
            *(dst + col) = c;
        }
    }
}

void screen_rect_alpha(int x, int y, int w, int h, uint32_t color, uint8_t alpha) {
    if (x < 0) { w += x; x = 0; }
    if (y < 0) { h += y; y = 0; }
    if (x + w > g_scr_w) w = g_scr_w - x;
    if (y + h > g_scr_h) h = g_scr_h - y;
    if (w <= 0 || h <= 0) return;

    uint32_t fg = apply_bright(color);
    uint32_t fr = (fg >> 16) & 0xFF;
    uint32_t fg_g = (fg >> 8) & 0xFF;
    uint32_t fb = fg & 0xFF;
    uint32_t inv = 255 - alpha;

    for (int row = 0; row < h; row++) {
        uint32_t *dst = back_buf + (y + row) * g_scr_w + x;
        for (int col = 0; col < w; col++) {
            uint32_t bg = *(dst + col);
            uint32_t r = (fr * alpha + ((bg >> 16) & 0xFF) * inv) >> 8;
            uint32_t g = (fg_g * alpha + ((bg >> 8) & 0xFF) * inv) >> 8;
            uint32_t b = (fb * alpha + (bg & 0xFF) * inv) >> 8;
            *(dst + col) = (r << 16) | (g << 8) | b;
        }
    }
}

void screen_round_rect(int x, int y, int w, int h, int r, uint32_t color) {
    if (w <= 0 || h <= 0) return;
    if (r <= 1 || w < r * 2 || h < r * 2) {
        screen_rect(x, y, w, h, color);
        return;
    }

    for (int row = 0; row < h; row++) {
        int inset = 0;
        if (row < r) {
            int dy = r - row - 1;
            while (inset < r && (r - inset - 1) * (r - inset - 1) + dy * dy > r * r) {
                inset++;
            }
        } else if (row >= h - r) {
            int dy = row - (h - r);
            while (inset < r && (r - inset - 1) * (r - inset - 1) + dy * dy > r * r) {
                inset++;
            }
        }
        screen_rect(x + inset, y + row, w - inset * 2, 1, color);
    }
}

static void draw_glyph8x8(int x, int y, const uint8_t *glyph, uint32_t color) {
    uint32_t c = apply_bright(color);
    for (int r = 0; r < 8; r++) {
        uint8_t bits = *(glyph + r);
        for (int col = 0; col < 8; col++) {
            if (bits & (1 << col)) {
                int px = x + col * 2;
                int py = y + r * 2;
                if (px >= 0 && px + 1 < g_scr_w && py >= 0 && py + 1 < g_scr_h) {
                    uint32_t *p = back_buf + py * g_scr_w + px;
                    *(p + 0) = c;
                    *(p + 1) = c;
                    *(p + g_scr_w + 0) = c;
                    *(p + g_scr_w + 1) = c;
                }
            }
        }
    }
}

void screen_char(int x, int y, char c, uint32_t color) {
    if (c < 32 || c > 126) return;
    draw_glyph8x8(x, y, font8x8[c - 32], color);
}

void screen_str(int x, int y, const char *s, uint32_t color) {
    int cx = x;
    int i = 0;
    while (*(s + i)) {
        uint8_t b0 = (uint8_t)*(s + i);
        if (b0 < 128) {
            screen_char(cx, y, (char)b0, color);
            cx += 16;
            i++;
        } else if (b0 == 0xD0 && *(s + i + 1)) {
            uint8_t b1 = (uint8_t)*(s + i + 1);
            int idx = -1;
            if (b1 == 0x81) idx = 64;
            else if (b1 >= 0x90 && b1 <= 0xBF) idx = b1 - 0x90;
            if (idx >= 0 && idx < 66) draw_glyph8x8(cx, y, ru_font[idx], color);
            cx += 16;
            i += 2;
        } else if (b0 == 0xD1 && *(s + i + 1)) {
            uint8_t b1 = (uint8_t)*(s + i + 1);
            int idx = -1;
            if (b1 == 0x91) idx = 65;
            else if (b1 >= 0x80 && b1 <= 0x8F) idx = 48 + (b1 - 0x80);
            if (idx >= 0 && idx < 66) draw_glyph8x8(cx, y, ru_font[idx], color);
            cx += 16;
            i += 2;
        } else {
            i++;
        }
    }
}

void screen_swap(void) {
    if (bpp == 32) {
        uint32_t pitch_dwords = pitch_bytes / 4;
        if (pitch_dwords == (uint32_t)g_scr_w) {
            uint32_t total = (uint32_t)(g_scr_w * g_scr_h);
            asm volatile ("cld; rep movsl" : : "S"(back_buf), "D"(lfb), "c"(total) : "memory");
        } else {
            for (int y = 0; y < g_scr_h; y++) {
                asm volatile ("cld; rep movsl" : : "S"(back_buf + y * g_scr_w), "D"(lfb + y * pitch_dwords), "c"(g_scr_w) : "memory");
            }
        }
    } else {
        uint8_t *dst_base = (uint8_t *)lfb;
        for (int y = 0; y < g_scr_h; y++) {
            uint32_t *src = back_buf + y * g_scr_w;
            uint8_t *dst = dst_base + y * pitch_bytes;
            for (int x = 0; x < g_scr_w; x++) {
                uint32_t c = *(src + x);
                *(dst + x * 3 + 0) = (uint8_t)(c & 0xFF);
                *(dst + x * 3 + 1) = (uint8_t)((c >> 8) & 0xFF);
                *(dst + x * 3 + 2) = (uint8_t)((c >> 16) & 0xFF);
            }
        }
    }
}